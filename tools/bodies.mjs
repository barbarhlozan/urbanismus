// Measures what each structure type's drawing covers on the ground and
// writes structures/bodies.js: its body, the walls a building placed freely
// keeps others and ways off (World.bodyBox). Run after changing a draw
// function:  node tools/bodies.mjs
//
// Each type is drawn (unjoined, on flat ground, no court) for many seeds
// and every kind it has; its Painter's bounds (all the solids drawn) are
// gathered, taken from the footprint's middle, given MARGIN all round and
// kept inside its plot. Sites (parks, squares) draw on the ground they're
// given and have no body: their whole plot is kept.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Camera } from '../src/render/camera.js';
import { Painter } from '../src/render/painter.js';
import { STRUCTURE_TYPES, footprintCenter } from '../structures/index.js';

const MARGIN = 0.04;
const SEEDS = 120;
const up = (v) => Math.ceil(v * 100 - 1e-6) / 100;

const rows = [];
for (const [id, def] of Object.entries(STRUCTURE_TYPES)) {
  if (def.site) continue;
  const kinds = def.kinds?.length ? [...new Set(def.kinds)] : [undefined];
  let b = null;
  for (let k = 0; k < SEEDS; k++) {
    const seed = 1 + k * 7919;
    for (const kind of kinds) {
      const g = new Painter(new Camera({ width: 30, height: 30 }), { x: 10, y: 10, z: 0 }, 0, seed);
      try {
        def.draw(g, { seed, type: id, rotation: 0, data: kind ? { kind } : {} });
      } catch {
        continue;
      }
      if (!g.bounds) continue;
      b = b ? [Math.min(b[0], g.bounds[0]), Math.min(b[1], g.bounds[1]), Math.max(b[2], g.bounds[2]), Math.max(b[3], g.bounds[3])] : [...g.bounds];
    }
  }
  if (!b) continue;
  const [cx, cy] = footprintCenter(def, 0);
  const offs = def.footprint ?? [[0, 0]];
  const half = (k) => (Math.max(...offs.map((o) => o[k])) - Math.min(...offs.map((o) => o[k])) + 1) / 2;
  const [hw, hh] = [half(0), half(1)];
  const box = [
    -Math.min(hw, up(cx - b[0] + MARGIN)),
    -Math.min(hh, up(cy - b[1] + MARGIN)),
    Math.min(hw, up(b[2] - cx + MARGIN)),
    Math.min(hh, up(b[3] - cy + MARGIN)),
  ];
  rows.push(`  '${id}': [${box.join(', ')}],`);
}

const out = `// Generated by tools/bodies.mjs – don't edit by hand, run it again.
//
// Each structure type's body: [x0, y0, x1, y1], local to its footprint's
// middle (front towards -y, unturned), what its drawing covers on the
// ground plus a margin. A building placed freely keeps other buildings and
// ways off its body (World.bodyBox, fitsOutline); its plot – the whole
// footprint – is still what it stands back from the road by and draws its
// garden in. A type left out (parks, squares) keeps its whole plot.

export const BODIES = {
${rows.join('\n')}
};
`;
writeFileSync(fileURLToPath(new URL('../structures/bodies.js', import.meta.url)), out);
console.log(`${rows.length} bodies`);
